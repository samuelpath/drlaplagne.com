const header = document.querySelector("[data-header]");
const menuButton = document.querySelector("[data-menu-button]");
const navigation = document.querySelector("[data-navigation]");
const navigationLinks = [...navigation.querySelectorAll("a")];
const languageButtons = [...document.querySelectorAll("[data-language]")];
const description = document.querySelector('meta[name="description"]');
const ogTitle = document.querySelector('meta[property="og:title"]');
const ogDescription = document.querySelector('meta[property="og:description"]');
const ogLocale = document.querySelector('meta[property="og:locale"]');
let currentLanguage = "fr";

const updateMailLinks = (language) => {
  const mail = mailContent[language];
  const href = `mailto:drlaplagne@gmail.com?subject=${encodeURIComponent(mail.subject)}&body=${encodeURIComponent(mail.body)}`;
  document.querySelectorAll("[data-mail-link]").forEach((link) => link.setAttribute("href", href));
};

const setLanguage = (language) => {
  currentLanguage = translations[language] ? language : "fr";
  const dictionary = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = dictionary.metaTitle;
  description.setAttribute("content", dictionary.metaDescription);
  ogTitle.setAttribute("content", dictionary.metaTitle);
  ogDescription.setAttribute("content", dictionary.ogDescription);
  ogLocale.setAttribute("content", dictionary.ogLocale);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-alt-key]").forEach((image) => {
    image.alt = dictionary[image.dataset.altKey] || image.alt;
  });

  document.querySelectorAll("[data-aria-key]").forEach((element) => {
    const value = dictionary[element.dataset.ariaKey];
    if (value) element.setAttribute("aria-label", value);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });

  updateMailLinks(currentLanguage);

  try {
    localStorage.setItem("medical-language", currentLanguage);
  } catch {}
};

const updateHeader = () => {
  header.classList.toggle("is-scrolled", window.scrollY > 24);
};

const closeMenu = () => {
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.querySelector(".sr-only").textContent = translations[currentLanguage]["a11y.openMenu"];
  navigation.classList.remove("is-open");
  document.body.classList.remove("menu-open");
};

menuButton.addEventListener("click", () => {
  const willOpen = menuButton.getAttribute("aria-expanded") === "false";
  menuButton.setAttribute("aria-expanded", String(willOpen));
  menuButton.querySelector(".sr-only").textContent = translations[currentLanguage][willOpen ? "a11y.closeMenu" : "a11y.openMenu"];
  navigation.classList.toggle("is-open", willOpen);
  document.body.classList.toggle("menu-open", willOpen);
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

navigationLinks.forEach((link) => link.addEventListener("click", closeMenu));

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 780) closeMenu();
});

window.addEventListener("scroll", updateHeader, { passive: true });
updateHeader();

const sections = [...document.querySelectorAll("main > section[id]")];
const sectionObserver = new IntersectionObserver(
  (entries) => {
    const visibleSection = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

    if (!visibleSection) return;

    navigationLinks.forEach((link) => {
      link.classList.toggle("is-active", link.hash === `#${visibleSection.target.id}`);
    });
  },
  { rootMargin: "-35% 0px -55%", threshold: [0, 0.25, 0.5] }
);

sections.forEach((section) => sectionObserver.observe(section));

